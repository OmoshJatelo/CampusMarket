import { HTMLAttributes, forwardRef } from 'react';
import { clsx } from 'clsx';

interface CardProps extends HTMLAttributes<HTMLDivElement> {
  variant?: 'default' | 'hover' | 'outlined';
  padding?: 'none' | 'sm' | 'md' | 'lg';
}

export const Card = forwardRef<HTMLDivElement, CardProps>(
  ({ children, variant = 'default', padding = 'md', className, ...props }, ref) => {
    const variantStyles = {
      default: 'bg-white border border-gray-200 shadow-card dark:bg-gray-800 dark:border-gray-700',
      hover: 'bg-white border border-gray-200 shadow-card hover:shadow-card-hover transition-shadow duration-200 dark:bg-gray-800 dark:border-gray-700',
      outlined: 'bg-white border-2 border-gray-200 dark:bg-gray-800 dark:border-gray-700',
    };

    const paddingStyles = {
      none: '',
      sm: 'p-3',
      md: 'p-5',
      lg: 'p-6',
    };

    return (
      <div
        ref={ref}
        className={clsx('rounded-2xl', variantStyles[variant], paddingStyles[padding], className)}
        {...props}
      >
        {children}
      </div>
    );
  }
);

Card.displayName = 'Card';

